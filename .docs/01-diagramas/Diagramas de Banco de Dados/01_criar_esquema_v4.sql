  "titulo" varchar(200) NOT NULL,
  "tipo" varchar(100) NOT NULL,
  "descricao" text,
  "criado_por_usuario_id" bigint NOT NULL,
  "criado_em" timestamptz NOT NULL DEFAULT (now()),
  "ativo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "versoes_governanca" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "documento_governanca_id" bigint NOT NULL,
  "numero_versao" integer NOT NULL,
  "conteudo" text NOT NULL,
  "status" status_versao_governanca NOT NULL DEFAULT 'RASCUNHO',
  "criada_por_usuario_id" bigint NOT NULL,
  "criada_em" timestamptz NOT NULL DEFAULT (now()),
  "aprovada_por_usuario_id" bigint,
  "aprovada_em" timestamptz,
  "publicada_em" timestamptz,
  CONSTRAINT "chk_numero_versao_positivo" CHECK (numero_versao >= 1),
  CONSTRAINT "chk_versao_publicada_aprovada" CHECK (status <> 'PUBLICADA' OR (aprovada_por_usuario_id IS NOT NULL AND aprovada_em IS NOT NULL AND publicada_em IS NOT NULL))
);

CREATE TABLE "historico_edicoes_governanca" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "versao_governanca_id" bigint NOT NULL,
  "editado_por_usuario_id" bigint NOT NULL,
  "resumo_alteracao" text NOT NULL,
  "registrado_em" timestamptz NOT NULL DEFAULT (now())
);

CREATE TABLE "aceites_governanca" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "versao_governanca_id" bigint NOT NULL,
  "usuario_id" bigint NOT NULL,
  "ciencia_em" timestamptz,
  "aceite_em" timestamptz
);

