CREATE FUNCTION proteger_advertencia_comunicada() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.comunicado_em IS NOT NULL THEN
        IF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'Advertência comunicada deve permanecer no histórico' USING ERRCODE = '23514';
        END IF;
        IF (NEW.texto_formal, NEW.usuario_id, NEW.tipo, NEW.comunicado_em, NEW.comunicado_por_usuario_id)
            IS DISTINCT FROM (OLD.texto_formal, OLD.usuario_id, OLD.tipo, OLD.comunicado_em, OLD.comunicado_por_usuario_id) THEN
            RAISE EXCEPTION 'Texto, destinatário e comunicação da advertência são imutáveis' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_advertencia_comunicada_imutavel
    BEFORE UPDATE OR DELETE ON registros_disciplinares
    FOR EACH ROW EXECUTE FUNCTION proteger_advertencia_comunicada();

