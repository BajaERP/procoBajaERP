CREATE FUNCTION proteger_versao_governanca_publicada() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = 'PUBLICADA' THEN
        IF TG_OP = 'DELETE' THEN
            RAISE EXCEPTION 'Versão de Governança publicada não pode ser excluída' USING ERRCODE = '23514';
        END IF;
        IF (to_jsonb(NEW) - ARRAY['vigencia_fim', 'fim_por_usuario_id', 'motivo_fim'])
            IS DISTINCT FROM (to_jsonb(OLD) - ARRAY['vigencia_fim', 'fim_por_usuario_id', 'motivo_fim']) THEN
            RAISE EXCEPTION 'Versão de Governança publicada é imutável' USING ERRCODE = '23514';
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_governanca_publicada_imutavel
    BEFORE UPDATE OR DELETE ON versoes_governanca
    FOR EACH ROW EXECUTE FUNCTION proteger_versao_governanca_publicada();
