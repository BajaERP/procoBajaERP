-- Governança e fontes do Dashboard
ALTER TABLE versoes_governanca
    ADD COLUMN pronta_em timestamptz,
    ADD COLUMN pronta_por_usuario_id bigint REFERENCES usuarios(id),
    ADD COLUMN vigencia_inicio timestamptz,
    ADD COLUMN vigencia_fim timestamptz,
    ADD COLUMN fim_por_usuario_id bigint REFERENCES usuarios(id),
    ADD COLUMN motivo_fim text;
WITH vigencias AS (
    SELECT id, publicada_em,
           lead(publicada_em) OVER (
               PARTITION BY documento_governanca_id ORDER BY publicada_em, numero_versao
           ) AS proxima_publicacao
    FROM versoes_governanca
    WHERE status = 'PUBLICADA'
)
UPDATE versoes_governanca v
SET vigencia_inicio = vigencias.publicada_em, vigencia_fim = vigencias.proxima_publicacao
FROM vigencias WHERE v.id = vigencias.id;
ALTER TABLE versoes_governanca
    ADD CONSTRAINT chk_governanca_pronta CHECK ((pronta_em IS NULL) = (pronta_por_usuario_id IS NULL)),
    ADD CONSTRAINT chk_governanca_vigencia CHECK (
        (status <> 'PUBLICADA' AND vigencia_inicio IS NULL AND vigencia_fim IS NULL)
        OR (status = 'PUBLICADA' AND vigencia_inicio IS NOT NULL AND vigencia_inicio >= publicada_em
            AND (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio))
    ),
    ADD CONSTRAINT chk_governanca_fim_motivado CHECK (
        (fim_por_usuario_id IS NULL AND motivo_fim IS NULL)
        OR (vigencia_fim IS NOT NULL AND fim_por_usuario_id IS NOT NULL
            AND coalesce(length(trim(motivo_fim)), 0) > 0)
    );
ALTER TABLE versoes_governanca
    ADD CONSTRAINT ex_governanca_vigencias_sobrepostas EXCLUDE USING gist (
        documento_governanca_id WITH =,
        tstzrange(vigencia_inicio, vigencia_fim, '[)') WITH &&
    ) WHERE (status = 'PUBLICADA');

